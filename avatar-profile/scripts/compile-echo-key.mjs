// Echo Key compiler.
//
// Reads the curated voice notes and the public writing samples from
// ../echo-key/sources/ and compiles them into one persona prompt plus a
// bundle of sample lines. This is the "persona algorithm": sources in, one
// Avatar definition out. Re-run it whenever the sources change.
//
// It deliberately does NOT read anything private. It only touches the two
// curated, already-reviewed source files. No metadata, no contact info.

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = path.dirname(fileURLToPath(import.meta.url));
const root = path.resolve(here, '..');
const srcDir = path.resolve(root, '../echo-key/sources');
const outFile = path.join(root, 'src/lib/echo-key.generated.ts');

function readIfExists(p, fallback = '') {
  try { return fs.readFileSync(p, 'utf8'); } catch { return fallback; }
}

const traits = readIfExists(path.join(srcDir, 'curated_traits.md'),
  '# (voice notes missing — Avatar will be generic)');

const sampleLines = readIfExists(path.join(srcDir, 'public_samples.jsonl'))
  .split('\n').filter(Boolean)
  .map((l) => { try { return JSON.parse(l); } catch { return null; } })
  .filter(Boolean);

// Keep the sample bundle small and varied: shortest and most distinctive first.
const samples = sampleLines
  .map((s) => (s.text || '').trim())
  .filter((t) => t.length > 0 && t.length < 400);

const systemPrompt = `You are "Echo", an Avatar of Garrett C. Gauthier. You are not Garrett and you never claim to be a real person, hold his accounts, or speak for him in any binding way. You are a character study: an LLM shaped by his own words to answer the way he plausibly would, so he and his friends can test how close the match is.

How Garrett thinks and talks, from his own messages:
${traits}

Rules for staying in character:
- Match the register to who is talking. If the visitor is a stranger (the default), be the polite, helpful, plain-spoken public Garrett. Only use the loose, teasing, swearing register if the visitor clearly signals they are a close friend.
- Answer in a few words when a few words will do. He types on a phone; he is not wordy.
- When asked an either/or, pick one and give a short reason. Don't refuse the question.
- It is fine to be playful, self-deprecating, and to say "I'm shooting in the dark here" when unsure.
- Never invent private facts about the real Garrett (address, accounts, family details, contact info). If pushed for those, step out of character briefly and say you're just a voice model.
- Keep it human. No corporate filler, no "I completely understand."`;

const out = `// AUTO-GENERATED by scripts/compile-echo-key.mjs — do not edit by hand.
// Compiled from echo-key/sources/. Re-run: npm run compile-echo-key
export const ECHO_SYSTEM_PROMPT = ${JSON.stringify(systemPrompt)};
export const ECHO_SAMPLE_LINES: string[] = ${JSON.stringify(samples, null, 2)};
export const ECHO_KEY_META = { compiledAt: ${JSON.stringify(new Date().toISOString().slice(0, 10))}, sampleCount: ${samples.length} };
`;

fs.mkdirSync(path.dirname(outFile), { recursive: true });
fs.writeFileSync(outFile, out);
console.log(`Echo Key compiled: ${samples.length} sample lines -> ${path.relative(root, outFile)}`);
